static_assert(sizeof(kGlyphs) / sizeof(kGlyphs[0]) == sizeof(kCharset) - 1,
              "glyph table and charset must stay in step");

// Unmapped characters render as '?' rather than disappearing: a note that comes
// out mangled is still evidence, a note that comes out blank is not.
int GlyphIndex(char c)
{
    if (c >= 'a' && c <= 'z')
        c = static_cast<char>(c - 'a' + 'A');
    for (int i = 0; kCharset[i] != '\0'; ++i)
    {
        if (kCharset[i] == c)
            return i;
    }
    return static_cast<int>(sizeof(kCharset)) - 2; // '?'
}

