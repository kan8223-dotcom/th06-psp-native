extern "C" void th06_psp_text_draw(int x, int y, int scale, unsigned int color, const char *text)
{
    volatile unsigned int *const fb = th06_psp_video_pixels();
    if (fb == nullptr || text == nullptr)
        return;
    if (scale < 1)
        scale = 1;

    const int stride = th06_psp_video_stride();
    const int screenW = th06_psp_video_width();
    const int screenH = th06_psp_video_height();
    int penX = x;

    for (const char *p = text; *p != '\0'; ++p)
    {
        if (*p == '\n')
        {
            penX = x;
            y += 7 * scale;
            continue;
        }
        const unsigned char *glyph = kGlyphs[GlyphIndex(*p)];
        for (int row = 0; row < 5; ++row)
        {
            const unsigned int bits = glyph[row];
            for (int col = 0; col < 4; ++col)
            {
                if ((bits & (0x8u >> col)) == 0)
                    continue;
                for (int sy = 0; sy < scale; ++sy)
                {
                    const int py = y + row * scale + sy;
                    if (py < 0 || py >= screenH)
                        continue;
                    volatile unsigned int *dst = fb + py * stride;
                    for (int sx = 0; sx < scale; ++sx)
                    {
                        const int px = penX + col * scale + sx;
                        if (px >= 0 && px < screenW)
                            dst[px] = color;
                    }
                }
            }
        }
        penX += 5 * scale;
    }
}

extern "C" void th06_psp_text_hex(int x, int y, int scale, unsigned int color, unsigned int value)
{
    char buffer[9];
    for (int i = 0; i < 8; ++i)
        buffer[i] = kCharset[(value >> ((7 - i) * 4)) & 0xFu];
    buffer[8] = '\0';
    th06_psp_text_draw(x, y, scale, color, buffer);
}
