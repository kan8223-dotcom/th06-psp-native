// One glyph per character of kCharset, in the same order.  Each glyph is a 4x6
// cell: five rows of pixels plus a blank row for line spacing, bit 3 leftmost.
// The punctuation is not decoration: paths, filenames and version stamps are
// most of what the boot record says, and a missing '/' or '.' turns a readable
// line into a guess.
constexpr char kCharset[] = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ :-=?/.,_()+<>*!%";

