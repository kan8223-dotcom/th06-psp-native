// Minimal bitmap text straight into the display buffer.
//
// The renderer exists so that a device with no USB connection, no debugger and
// no working HOME button can still tell us *where* it stopped.  It therefore
// performs no allocation and issues no kernel call, which also makes it legal
// to call from an exception handler.
#include "diag.hpp"
#include "video.hpp"

